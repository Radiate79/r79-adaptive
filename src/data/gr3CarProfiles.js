/**
 * Look up a Gr.3 car profile by car ID.
 * Returns null if no profile exists for this car.
 * @param {string} carId
 * @returns {Gr3CarProfile|null}
 */
export function getGr3CarProfile(carId) {
  return GR3_CAR_PROFILES.find((p) => p.carId === carId) ?? null;
}

/**
 * Return all Gr.3 car IDs that have authoritative profiles.
 * @returns {string[]}
 */
export function getGr3ProfiledCarIds() {
  return GR3_CAR_PROFILES.map((p) => p.carId);
}
